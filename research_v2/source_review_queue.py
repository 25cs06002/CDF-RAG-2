"""Build a source-review worklist for the direct/paraphrased pilot.

Candidate URLs have been located on official public-health websites, but
their suitability for any medical claim is NOT yet independently reviewed.
No gold labels or medical evidence are generated by this module.
"""

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, HttpUrl

from .medical_benchmark import file_sha256
from .pilot_preparation import validate_pilot


class SourceCandidate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    source_id: str = Field(min_length=1)
    target_concept: str = Field(min_length=1)
    medical_domain: str = Field(min_length=1)
    title: str = Field(min_length=1)
    url: HttpUrl
    source_type: Literal["public_health"]
    coverage_type: Literal["causes", "risk_factors", "triggers", "mixed"]
    scope_note: str = Field(min_length=1)
    candidate_status: Literal["awaiting_source_review"]
    gold_annotation_status: Literal["none"]
    verified_medical_gold: Literal[False]


def load_candidate_sources(path: Path) -> list[SourceCandidate]:
    records = []
    with Path(path).open(encoding="utf-8") as stream:
        for number, line in enumerate(stream, 1):
            if not line.strip():
                continue
            try:
                records.append(SourceCandidate.model_validate_json(line))
            except Exception as exc:
                raise ValueError(
                    f"Invalid candidate source at line {number}: {exc}"
                ) from exc

    if not records:
        raise ValueError("Empty source candidate registry")

    ids = [r.source_id for r in records]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate candidate source ID")

    urls = [str(r.url).rstrip("/").casefold() for r in records]
    if len(urls) != len(set(urls)):
        raise ValueError("Duplicate candidate source URL")

    topics = [r.target_concept.casefold().strip() for r in records]
    if len(topics) != len(set(topics)):
        raise ValueError("Duplicate candidate target_concept")

    return records


def build_source_review_queue(pilot_file: Path, candidates_file: Path):
    pilot, pilot_profile = validate_pilot(pilot_file)
    sources = load_candidate_sources(candidates_file)

    source_by_topic = {
        source.target_concept.casefold().strip(): source
        for source in sources
    }

    selected = [
        record for record in pilot
        if record.query_type in {"direct", "paraphrased"}
    ]

    if len(selected) != 30:
        raise ValueError("Expected 30 direct/paraphrased questions")
    if len(sources) != 15:
        raise ValueError("Expected 15 source candidates")

    result = []

    for record in selected:
        key = (record.target_concept or "").casefold().strip()
        source = source_by_topic.get(key)
        if source is None:
            raise ValueError(
                f"Missing candidate source for {record.query_id}: "
                f"{record.target_concept}"
            )
        if source.medical_domain != record.medical_domain:
            raise ValueError(
                f"Medical domain mismatch for {record.query_id}"
            )

        result.append({
            "query_id": record.query_id,
            "query": record.query,
            "query_type": record.query_type,
            "medical_domain": record.medical_domain,
            "target_concept": record.target_concept,
            "question_family": record.question_family,
            "candidate_source": source.model_dump(mode="json"),
            "review_tasks": [
                "Read the source and verify its scope and date",
                "Determine whether the question is answerable from this source",
                "Distinguish cause, association, risk factor and trigger",
                "Record attributable claims, limitations and correct source ID",
                "Escalate unsupported causal claims for additional sources",
            ],
            "source_review_completed": False,
            "medical_gold_created": False,
        })

    if len({r["query_id"] for r in result}) != 30:
        raise ValueError("Duplicate query ID in source-review queue")

    profile = {
        "schema_version": 1,
        "data_role": "unreviewed_source_candidate_queue",
        "review_questions": len(result),
        "distinct_source_candidates": len(sources),
        "query_type_counts": dict(sorted(Counter(
            r["query_type"] for r in result
        ).items())),
        "pilot_sha256": pilot_profile["dataset_sha256"],
        "source_candidates_sha256": file_sha256(candidates_file),
        "source_review_completed": False,
        "medical_gold_created": False,
        "final_splits_assigned": False,
        "note": (
            "Official website links are candidate reading material, "
            "not clinical verification or accepted causal gold labels."
        ),
    }

    return result, profile


def write_source_review_queue(
    pilot_file: Path, candidates_file: Path, output_dir: Path
):
    rows, profile = build_source_review_queue(pilot_file, candidates_file)
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=False)

    (root / "source_review_queue.jsonl").write_text(
        "".join(
            json.dumps(row, ensure_ascii=False) + "\n"
            for row in rows
        ),
        encoding="utf-8",
    )
    (root / "source_review_profile.json").write_text(
        json.dumps(profile, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return profile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--pilot", type=Path,
        default=Path("data/benchmark/medical_causal_pilot100_draft_v1.jsonl"),
    )
    parser.add_argument(
        "--candidates", type=Path,
        default=Path("data/benchmark/source_candidates15_v1.jsonl"),
    )
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()

    if args.output_dir is None:
        _, profile = build_source_review_queue(args.pilot, args.candidates)
    else:
        profile = write_source_review_queue(
            args.pilot, args.candidates, args.output_dir
        )

    print(json.dumps(profile, indent=2))


if __name__ == "__main__":
    main()
